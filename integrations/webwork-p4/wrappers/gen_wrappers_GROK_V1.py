#!/usr/bin/env python3
"""GROK_V1 P4 wrapper generator (V1_1: --description for the set, used for the P13 menu test set): one WeBWorK .pg per OEF exercise, from the SQLite catalogue (source='oef' rows).
Usage: gen_wrappers_GROK_V1.py --catalog CAT.sqlite --out DIR [--setdef FILE] MODULE:EXO ...
Each item must exist in the catalogue (path MODULE/src/EXO.oef); title/keywords/level come from it."""
import argparse, sqlite3, sys
from pathlib import Path

TEMPLATE = """## GROK_V1 P4 wrapper (generated by gen_wrappers_GROK_V1.py; do not edit by hand)
## DESCRIPTION
## {title}
## ENDDESCRIPTION
## DBsubject('WIMS OEF')
## DBchapter('{module}')
## DBsection('{exo}')
## KEYWORDS({keywords})
## Level({level})
## Language({language})
## Author(WIMS OEF author: {author})
## Institution(WIMS public module {module})
DOCUMENT();
loadMacros('PGstandard.pl', 'oefRemote.pl');
TEXT(beginproblem());
$oef = OEF('{module}', '{exo}');
TEXT($oef->statement);
$oef->ANS;
ENDDOCUMENT();
"""


def q(s):
    return (s or "").replace("\\", "").replace("'", "").replace("\n", " ").strip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--catalog", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--setdef")
    ap.add_argument("--description", default="GROK_V1 P4 pilot: WIMS OEF exercises graded by WIMS, scores in WeBWorK")
    ap.add_argument("items", nargs="+")
    a = ap.parse_args()
    con = sqlite3.connect(f"file:{a.catalog}?mode=ro", uri=True)
    out = Path(a.out)
    paths = []
    for it in a.items:
        module, exo = it.split(":", 1)
        row = con.execute("select title, keywords, level, language, author from items where source='oef' and path=?",
                          (f"{module}/src/{exo}.oef",)).fetchone()
        if not row:
            sys.exit(f"not in catalogue: {it}")
        title, kw, level, lang, author = row
        rel = Path("OEF") / module / f"{exo}.pg"
        dest = out / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        kws = ",".join("'" + q(k) + "'" for k in (kw or "").split(",") if q(k))[:400]
        dest.write_text(TEMPLATE.format(title=q(title) or exo, module=module, exo=exo, keywords=kws,
                                        level=q(level), language=q(lang) or "fr", author=q(author)), encoding="utf-8")
        paths.append(rel.as_posix())
        print(f"{rel}  <- {q(title)}")
    if a.setdef:
        lines = ["assignmentType = default", "openDate          = 11/01/2026 at 12:00am CET",
                 "reducedScoringDate =", "dueDate           = 11/01/2027 at 12:00am CET",
                 "answerDate        = 11/02/2027 at 12:00am CET", "paperHeaderFile   =", "screenHeaderFile  =",
                 f"description = {a.description}", "",
                 "problemListV2"]
        for p in paths:
            lines += ["problem_start", f"source_file = {p}", "value = 1", "max_attempts = -1", "problem_end"]
        Path(a.setdef).write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"set def: {a.setdef} ({len(paths)} problems)")


if __name__ == "__main__":
    main()
